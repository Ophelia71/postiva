SET LOCAL lock_timeout = '5s';

ALTER TABLE subscription_periods
    ADD COLUMN voided_at TIMESTAMPTZ,
    ADD COLUMN void_reason VARCHAR(40);

CREATE TABLE payment_orders (
    id UUID PRIMARY KEY,
    order_code BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000) UNIQUE,
    user_id UUID NOT NULL REFERENCES users(id),
    idempotency_key UUID NOT NULL,
    provider VARCHAR(20) NOT NULL DEFAULT 'PAYOS' CHECK (provider = 'PAYOS'),
    provider_environment VARCHAR(10) NOT NULL DEFAULT 'LIVE' CHECK (provider_environment = 'LIVE'),
    plan_code VARCHAR(10) NOT NULL DEFAULT 'PRO' CHECK (plan_code = 'PRO'),
    amount_vnd BIGINT NOT NULL CHECK (amount_vnd > 0),
    ai_limit INTEGER NOT NULL CHECK (ai_limit >= 0),
    period_days INTEGER NOT NULL CHECK (period_days BETWEEN 1 AND 366),
    status VARCHAR(20) NOT NULL DEFAULT 'CREATING'
        CHECK (status IN ('CREATING', 'PENDING', 'PAID', 'CANCELLED', 'EXPIRED', 'REVIEW')),
    grant_status VARCHAR(20) NOT NULL DEFAULT 'NOT_APPLICABLE'
        CHECK (grant_status IN ('NOT_APPLICABLE', 'PENDING', 'GRANTED', 'FAILED')),
    provider_link_id VARCHAR(100) UNIQUE,
    provider_transaction_ref VARCHAR(160) UNIQUE,
    recipient_account_number VARCHAR(60),
    checkout_url TEXT,
    provider_attempt_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    paid_at TIMESTAMPTZ,
    granted_period_id UUID UNIQUE REFERENCES subscription_periods(id),
    last_reconciled_at TIMESTAMPTZ,
    review_reason VARCHAR(80),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, idempotency_key),
    CHECK (status <> 'PAID' OR provider_transaction_ref IS NOT NULL)
);
CREATE INDEX idx_payment_orders_user_created ON payment_orders (user_id, created_at DESC);
CREATE INDEX idx_payment_orders_reconcile ON payment_orders (last_reconciled_at, created_at)
    WHERE status IN ('CREATING', 'PENDING', 'PAID', 'EXPIRED', 'CANCELLED', 'REVIEW');
CREATE UNIQUE INDEX idx_payment_orders_one_open ON payment_orders (user_id)
    WHERE status IN ('CREATING', 'PENDING');

CREATE TABLE payment_events (
    id UUID PRIMARY KEY,
    order_id UUID REFERENCES payment_orders(id),
    event_kind VARCHAR(30) NOT NULL,
    signature_sha256 CHAR(64) NOT NULL UNIQUE,
    provider_reference VARCHAR(160),
    amount_vnd BIGINT,
    decision VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_payment_events_order ON payment_events (order_id, created_at DESC);

CREATE TABLE payment_refunds (
    id UUID PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES payment_orders(id),
    amount_vnd BIGINT NOT NULL CHECK (amount_vnd > 0),
    status VARCHAR(20) NOT NULL CHECK (status IN
        ('REQUESTED', 'APPROVED', 'PROCESSING', 'SUCCEEDED', 'REJECTED', 'FAILED')),
    reason VARCHAR(1000) NOT NULL,
    provider_ref VARCHAR(160) UNIQUE,
    requested_by UUID NOT NULL REFERENCES users(id),
    reviewed_by UUID REFERENCES users(id),
    settled_by UUID REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ,
    settled_at TIMESTAMPTZ
);
CREATE INDEX idx_payment_refunds_order ON payment_refunds (order_id, created_at DESC);

CREATE TABLE payment_admin_audit (
    id UUID PRIMARY KEY,
    actor_user_id UUID NOT NULL REFERENCES users(id),
    order_id UUID NOT NULL REFERENCES payment_orders(id),
    refund_id UUID REFERENCES payment_refunds(id),
    action VARCHAR(40) NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_payment_admin_audit_order ON payment_admin_audit (order_id, created_at DESC);
